-- =====================================================
-- NSS ERP
-- Module: Administration (Correspondence Register capability)
-- File: 01_correspondence.sql
-- Table: nss.correspondence
-- Depth: 4 (depends on person, organization, master_data)
-- Version: 1.0
-- Authority: SOL-ADMIN-009 §4, SOL-ADMIN-008 (business rules),
--            CORR-DECISION-003 (capability acceptance),
--            Tier placement: Tier 6 (owner-confirmed 2026-10-16,
--            moved from Tier 5 — see IMPLEMENTATION_DEPENDENCY_ORDER.md §44)
-- Owner: Administration
--
-- Design decisions:
--   - reference_number is system-generated by the application
--     service (per-organization, per-direction, per-annual-period
--     counter, format <ORG_SHORT_CODE>/{IN|OUT}/YYYY-YY/NNN per
--     CORR-EXT-001 / §4.9; supersedes the earlier global
--     NSS/{IN|OUT}/YYYY-YY/NNN format), immutable once assigned.
--     No FK to id_sequence_master — application/service dependency
--     only (SOL-ADMIN-009 §2).
--   - sender_type/recipient_type use a compound CHECK enforcing
--     exactly one of {person FK, organization FK, external free
--     text} per party, per SOL-ADMIN-009 §4.6.
--   - medium and status resolve via Foundation master_data (extensible
--     sets); direction is a fixed CHECK (will not change).
--   - No ON DELETE CASCADE anywhere — referenced person/organization/
--     master_data rows cannot be removed while correspondence
--     references them (SOL-ADMIN-009 §10).
--   - CORR-BR-015: hard-delete is not permitted; soft-delete only.
--
-- Note: Audit actor FKs (*_by_sangha_sevi_pk) are NULLABLE columns
--       included in Pass 1. Their FK constraints are deferred to
--       Pass 2, per project-wide two-pass DDL convention.
-- =====================================================

CREATE TABLE IF NOT EXISTS nss.correspondence
(
    -- ── Identity ────────────────────────────────────────

    correspondence_pk UUID PRIMARY KEY
        DEFAULT gen_random_uuid(),

    -- Which organization's correspondence register this record is
    -- filed under. Always populated — this is the organization whose
    -- per-direction, per-annual-period counter mints reference_number
    -- (CORR-BR-003 / CORR-EXT-001), and the scope boundary for admin
    -- access (owner-confirmed 2026-10-17: an org admin sees their own
    -- scope's inward and outward register only).
    --
    -- Deliberately distinct from sender/recipient/responsible org:
    -- those are conditional (NULL unless *_type = 'ORGANIZATION') and
    -- answer "who wrote/received it" or "who must act"; this answers
    -- "whose register is it", which must never be NULL.
    register_organization_pk UUID NOT NULL,

    reference_number VARCHAR(40) NOT NULL,

    -- ── Correspondence Details ──────────────────────────

    direction VARCHAR(10) NOT NULL,

    correspondence_date DATE NOT NULL,

    received_or_sent_date DATE NOT NULL,

    follow_up_date DATE NULL,

    subject VARCHAR(255) NOT NULL,

    remarks TEXT NULL,

    -- ── Sender ──────────────────────────────────────────

    sender_type VARCHAR(20) NOT NULL,

    sender_person_pk UUID NULL,

    sender_organization_pk UUID NULL,

    sender_external_name VARCHAR(150) NULL,

    sender_external_organization VARCHAR(150) NULL,

    -- Only populated when sender_type = 'PERSON'. Capacity in which
    -- the person wrote — on their own behalf, or representing an
    -- organization (which organization is sender_person_organization_pk).
    -- Owner-confirmed 2026-10-17, added for office-bearer-application
    -- traceability (CORR-DECISION-004 Track 2 context) but useful for
    -- the register generally. The person's NAME is deliberately NOT
    -- duplicated here — sender_person_pk already resolves it via
    -- person; storing it again would violate Master Data Driven.
    sender_person_capacity VARCHAR(20) NULL,

    sender_person_organization_pk UUID NULL,

    -- Point-in-time snapshot of the sender's Local Sakha ID at the
    -- time of writing, if they were an active Sangha Sevi. Mirrors
    -- the existing snapshot pattern on parichaya_patra.local_sakha_erp_id
    -- and membership_transfer_history.old/new_local_sakha_erp_id — not
    -- a live FK, so it survives the sender's later Sakha transfer
    -- unchanged. UI resolves this to the Sakha name for display.
    sender_sakha_erp_id_snapshot VARCHAR(30) NULL,

    -- ── Recipient ───────────────────────────────────────

    recipient_type VARCHAR(20) NOT NULL,

    recipient_person_pk UUID NULL,

    recipient_organization_pk UUID NULL,

    recipient_external_name VARCHAR(150) NULL,

    recipient_external_organization VARCHAR(150) NULL,

    -- ── Responsibility / Classification ─────────────────

    responsible_person_pk UUID NULL,

    responsible_organization_pk UUID NULL,

    medium_master_data_pk UUID NOT NULL,

    status_master_data_pk UUID NOT NULL,

    -- ── Audit ───────────────────────────────────────────

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    created_by_sangha_sevi_pk UUID NULL,

    updated_at TIMESTAMPTZ NULL,

    updated_by_sangha_sevi_pk UUID NULL,

    deleted_at TIMESTAMPTZ NULL,

    deleted_by_sangha_sevi_pk UUID NULL,

    is_active BOOLEAN NOT NULL
        DEFAULT TRUE,

    -- ── Foreign Keys ────────────────────────────────────

    CONSTRAINT fk_correspondence_register_organization
        FOREIGN KEY (register_organization_pk)
        REFERENCES nss.organization (organization_pk),

    CONSTRAINT fk_correspondence_sender_person
        FOREIGN KEY (sender_person_pk)
        REFERENCES nss.person (person_pk),

    CONSTRAINT fk_correspondence_sender_organization
        FOREIGN KEY (sender_organization_pk)
        REFERENCES nss.organization (organization_pk),

    CONSTRAINT fk_correspondence_sender_person_organization
        FOREIGN KEY (sender_person_organization_pk)
        REFERENCES nss.organization (organization_pk),

    CONSTRAINT fk_correspondence_recipient_person
        FOREIGN KEY (recipient_person_pk)
        REFERENCES nss.person (person_pk),

    CONSTRAINT fk_correspondence_recipient_organization
        FOREIGN KEY (recipient_organization_pk)
        REFERENCES nss.organization (organization_pk),

    CONSTRAINT fk_correspondence_responsible_person
        FOREIGN KEY (responsible_person_pk)
        REFERENCES nss.person (person_pk),

    CONSTRAINT fk_correspondence_responsible_organization
        FOREIGN KEY (responsible_organization_pk)
        REFERENCES nss.organization (organization_pk),

    CONSTRAINT fk_correspondence_medium
        FOREIGN KEY (medium_master_data_pk)
        REFERENCES nss.master_data (master_data_pk),

    CONSTRAINT fk_correspondence_status
        FOREIGN KEY (status_master_data_pk)
        REFERENCES nss.master_data (master_data_pk),

    -- ── Unique Constraints ──────────────────────────────

    CONSTRAINT uq_correspondence_reference_number
        UNIQUE (reference_number),

    -- ── CHECK Constraints ───────────────────────────────

    CONSTRAINT chk_correspondence_direction
        CHECK (direction IN ('INWARD', 'OUTWARD')),

    CONSTRAINT chk_correspondence_sender_type
        CHECK (sender_type IN ('PERSON', 'ORGANIZATION', 'EXTERNAL')),

    CONSTRAINT chk_correspondence_recipient_type
        CHECK (recipient_type IN ('PERSON', 'ORGANIZATION', 'EXTERNAL')),

    CONSTRAINT chk_correspondence_sender_person_capacity
        CHECK (sender_person_capacity IN ('PERSONAL', 'ORGANIZATIONAL')),

    -- sender_person_capacity / sender_person_organization_pk /
    -- sender_sakha_erp_id_snapshot only make sense when sender_type =
    -- 'PERSON'; for ORGANIZATION/EXTERNAL senders they must be NULL.
    CONSTRAINT chk_correspondence_sender_person_detail_consistency
        CHECK
        (
            (
                sender_type = 'PERSON'
                AND sender_person_capacity IS NOT NULL
            )
            OR
            (
                sender_type <> 'PERSON'
                AND sender_person_capacity IS NULL
                AND sender_person_organization_pk IS NULL
                AND sender_sakha_erp_id_snapshot IS NULL
            )
        ),

    -- sender_person_organization_pk is required when capacity is
    -- ORGANIZATIONAL and forbidden when PERSONAL.
    CONSTRAINT chk_correspondence_sender_person_capacity_org
        CHECK
        (
            sender_person_capacity IS NULL
            OR
            (sender_person_capacity = 'ORGANIZATIONAL' AND sender_person_organization_pk IS NOT NULL)
            OR
            (sender_person_capacity = 'PERSONAL' AND sender_person_organization_pk IS NULL)
        ),

    -- Sender conditional integrity (SOL-ADMIN-009 §4.6): exactly one
    -- of {person, organization, external} per sender_type.
    CONSTRAINT chk_correspondence_sender_consistency
        CHECK
        (
            (
                sender_type = 'PERSON'
                AND sender_person_pk IS NOT NULL
                AND sender_organization_pk IS NULL
                AND sender_external_name IS NULL
                AND sender_external_organization IS NULL
            )
            OR
            (
                sender_type = 'ORGANIZATION'
                AND sender_person_pk IS NULL
                AND sender_organization_pk IS NOT NULL
                AND sender_external_name IS NULL
                AND sender_external_organization IS NULL
            )
            OR
            (
                sender_type = 'EXTERNAL'
                AND sender_person_pk IS NULL
                AND sender_organization_pk IS NULL
                AND sender_external_name IS NOT NULL
            )
        ),

    -- Recipient conditional integrity (SOL-ADMIN-009 §4.6): exactly
    -- one of {person, organization, external} per recipient_type.
    CONSTRAINT chk_correspondence_recipient_consistency
        CHECK
        (
            (
                recipient_type = 'PERSON'
                AND recipient_person_pk IS NOT NULL
                AND recipient_organization_pk IS NULL
                AND recipient_external_name IS NULL
                AND recipient_external_organization IS NULL
            )
            OR
            (
                recipient_type = 'ORGANIZATION'
                AND recipient_person_pk IS NULL
                AND recipient_organization_pk IS NOT NULL
                AND recipient_external_name IS NULL
                AND recipient_external_organization IS NULL
            )
            OR
            (
                recipient_type = 'EXTERNAL'
                AND recipient_person_pk IS NULL
                AND recipient_organization_pk IS NULL
                AND recipient_external_name IS NOT NULL
            )
        ),

    CONSTRAINT chk_correspondence_soft_delete
        CHECK
        (
            (is_active = TRUE AND deleted_at IS NULL)
            OR
            (is_active = FALSE AND deleted_at IS NOT NULL)
        )
);

-- ── Indexes ─────────────────────────────────────────────
-- (reference_number is already covered by uq_correspondence_reference_number.
--  reference_number stays globally UNIQUE even though counters are
--  per-organization: the org short code is embedded in the value, so
--  KEN/IN/2026-27/001 and ESS/IN/2026-27/001 never collide — see
--  business rules §13.3.)

-- Primary access path: "show organization X's inward (or outward)
-- register, newest first". register_organization_pk leads, so this
-- also serves plain register_organization_pk lookups and the
-- admin-scope filter — no separate single-column index needed.
CREATE INDEX IF NOT EXISTS idx_correspondence_register_direction_date
    ON nss.correspondence (register_organization_pk, direction, correspondence_date DESC);

CREATE INDEX IF NOT EXISTS idx_correspondence_direction
    ON nss.correspondence (direction);

CREATE INDEX IF NOT EXISTS idx_correspondence_status
    ON nss.correspondence (status_master_data_pk);

CREATE INDEX IF NOT EXISTS idx_correspondence_responsible_person
    ON nss.correspondence (responsible_person_pk)
    WHERE responsible_person_pk IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_correspondence_responsible_org
    ON nss.correspondence (responsible_organization_pk)
    WHERE responsible_organization_pk IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_correspondence_correspondence_date
    ON nss.correspondence (correspondence_date);

CREATE INDEX IF NOT EXISTS idx_correspondence_sender_person
    ON nss.correspondence (sender_person_pk)
    WHERE sender_person_pk IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_correspondence_sender_sakha_snapshot
    ON nss.correspondence (sender_sakha_erp_id_snapshot)
    WHERE sender_sakha_erp_id_snapshot IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_correspondence_recipient_person
    ON nss.correspondence (recipient_person_pk)
    WHERE recipient_person_pk IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_correspondence_active
    ON nss.correspondence (is_active);
